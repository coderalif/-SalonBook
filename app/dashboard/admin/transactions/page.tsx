'use client';

// ========================================================
// Admin Transactions Page (Stripe পেমেন্ট হিস্ট্রি ও ট্রানজেকশন)
// ========================================================

import React, { useState, useEffect } from 'react';
import { apiFetch } from '@/lib/api';
import {
    Receipt,
    CheckCircle,
    XCircle,
    Calendar,
    CreditCard,
    DollarSign,
    Loader2,
    Lock
} from 'lucide-react';
import toast from 'react-hot-toast';

interface TransactionItem {
    _id: string;
    appointmentId: {
        _id: string;
        appointmentDate: string;
        timeSlot: string;
        serviceId?: {
            serviceName: string;
            category: string;
        };
    } | null;
    customerId: {
        _id: string;
        name: string;
        email: string;
        image?: string;
    } | null;
    amount: number;
    currency: string;
    stripeSessionId: string;
    status: 'paid' | 'failed';
    createdAt: string;
}

export default function AdminTransactionsPage() {
    const [transactions, setTransactions] = useState<TransactionItem[]>([]);
    const [loading, setLoading] = useState(true);

    useEffect(() => {
        const fetchTransactions = async () => {
            try {
                setLoading(true);
                const res = await apiFetch('/payments/transactions');
                if (res.success && res.transactions) {
                    setTransactions(res.transactions);
                }
            } catch (error) {
                console.error('Failed to load transactions:', error);
                toast.error('Failed to load transaction audit records');
            } finally {
                setLoading(false);
            }
        };

        fetchTransactions();
    }, []);

    // মোট রেভিনিউ গণনা
    const totalRevenue = transactions
        .filter((t) => t.status === 'paid')
        .reduce((sum, t) => sum + (t.amount || 0), 0);

    return (
        <div className="space-y-6">
            
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-2 border-b border-gray-100">
                <div>
                    <h1 className="text-2xl sm:text-3xl font-extrabold text-gray-900 tracking-tight">
                        Payment Transactions Audit
                    </h1>
                    <p className="text-sm text-gray-500 mt-1">
                        Verified Stripe checkout transactions logged via automated webhooks.
                    </p>
                </div>

                <div className="bg-emerald-50 border border-emerald-200 px-5 py-2.5 rounded-2xl flex items-center gap-3">
                    <div className="w-9 h-9 rounded-xl bg-emerald-600 text-white flex items-center justify-center">
                        <DollarSign className="w-5 h-5" />
                    </div>
                    <div>
                        <p className="text-[11px] text-emerald-800 font-semibold uppercase">Total Settled Revenue</p>
                        <p className="text-lg font-extrabold text-emerald-900">${totalRevenue.toLocaleString()}</p>
                    </div>
                </div>
            </div>

            {/* সিকিউরিটি নোট */}
            <div className="p-4 bg-amber-50/70 border border-amber-200 rounded-2xl flex items-center gap-3 text-xs text-amber-800">
                <Lock className="w-4 h-4 shrink-0 text-amber-700" />
                <span>
                    <strong>Audit-Safe Security Notice:</strong> Transaction records are permanently generated by verified Stripe webhooks. In compliance with security standards, administrators cannot manually alter or manipulate transaction statuses.
                </span>
            </div>

            {loading ? (
                <div className="bg-white rounded-3xl p-12 text-center border border-gray-100">
                    <Loader2 className="w-8 h-8 text-rose-600 animate-spin mx-auto mb-3" />
                    <p className="text-sm text-gray-500">Loading verified transaction ledger...</p>
                </div>
            ) : transactions.length > 0 ? (
                <div className="bg-white rounded-3xl border border-gray-100 shadow-sm overflow-hidden">
                    <div className="overflow-x-auto">
                        <table className="w-full text-left text-sm">
                            <thead className="bg-gray-50/70 text-gray-500 text-xs uppercase tracking-wider border-b border-gray-100">
                                <tr>
                                    <th className="px-6 py-4">Customer</th>
                                    <th className="px-6 py-4">Related Service</th>
                                    <th className="px-6 py-4">Session Date</th>
                                    <th className="px-6 py-4">Amount Paid</th>
                                    <th className="px-6 py-4">Stripe Reference</th>
                                    <th className="px-6 py-4">Payment Status</th>
                                    <th className="px-6 py-4 text-right">Transaction Time</th>
                                </tr>
                            </thead>
                            <tbody className="divide-y divide-gray-100">
                                {transactions.map((tx) => (
                                    <tr key={tx._id} className="hover:bg-slate-50/50 transition-colors">
                                        {/* কাস্টমার */}
                                        <td className="px-6 py-4">
                                            <div className="flex items-center gap-3">
                                                <img
                                                    src={tx.customerId?.image || 'https://i.ibb.co.com/4pDNDk1/avatar-placeholder.png'}
                                                    alt="User"
                                                    className="w-9 h-9 rounded-full object-cover border shrink-0"
                                                />
                                                <div>
                                                    <p className="font-bold text-gray-900">{tx.customerId?.name || 'Customer'}</p>
                                                    <p className="text-xs text-gray-400">{tx.customerId?.email}</p>
                                                </div>
                                            </div>
                                        </td>

                                        {/* সার্ভিস */}
                                        <td className="px-6 py-4">
                                            <p className="font-semibold text-gray-900">
                                                {tx.appointmentId?.serviceId?.serviceName || 'Salon Service'}
                                            </p>
                                            <span className="text-[11px] text-rose-600">
                                                {tx.appointmentId?.serviceId?.category}
                                            </span>
                                        </td>

                                        {/* সেশন তারিখ */}
                                        <td className="px-6 py-4 text-xs text-gray-600">
                                            {tx.appointmentId?.appointmentDate || 'N/A'}
                                        </td>

                                        {/* অ্যামাউন্ট */}
                                        <td className="px-6 py-4">
                                            <span className="font-extrabold text-emerald-600 text-base">
                                                ${tx.amount}
                                            </span>
                                            <span className="text-xs text-gray-400 uppercase ml-1">
                                                {tx.currency}
                                            </span>
                                        </td>

                                        {/* স্ট্রাইপ সেশন আইডি (Shortened) */}
                                        <td className="px-6 py-4">
                                            <code className="text-xs font-mono bg-gray-100 px-2 py-1 rounded text-gray-700">
                                                {tx.stripeSessionId ? `${tx.stripeSessionId.slice(0, 14)}...` : 'N/A'}
                                            </code>
                                        </td>

                                        {/* পেমেন্ট অবস্থা */}
                                        <td className="px-6 py-4">
                                            <span
                                                className={`inline-flex items-center gap-1 px-3 py-1 rounded-full text-xs font-bold ${
                                                    tx.status === 'paid'
                                                        ? 'bg-emerald-50 text-emerald-700 border border-emerald-200'
                                                        : 'bg-rose-50 text-rose-700 border border-rose-200'
                                                }`}
                                            >
                                                {tx.status === 'paid' ? (
                                                    <>
                                                        <CheckCircle className="w-3.5 h-3.5" /> Successful
                                                    </>
                                                ) : (
                                                    <>
                                                        <XCircle className="w-3.5 h-3.5" /> Failed
                                                    </>
                                                )}
                                            </span>
                                        </td>

                                        {/* ট্রানজেকশন তারিখ */}
                                        <td className="px-6 py-4 text-right text-xs text-gray-500 font-medium">
                                            {new Date(tx.createdAt).toLocaleString()}
                                        </td>
                                    </tr>
                                ))}
                            </tbody>
                        </table>
                    </div>
                </div>
            ) : (
                <div className="bg-white rounded-3xl p-12 text-center border border-gray-100 space-y-4">
                    <Receipt className="w-12 h-12 text-gray-400 mx-auto" />
                    <h3 className="text-xl font-bold text-gray-900">No Transactions Logged Yet</h3>
                    <p className="text-sm text-gray-500">
                        When customers complete payments for confirmed appointments via Stripe, records will appear here automatically.
                    </p>
                </div>
            )}

        </div>
    );
}
